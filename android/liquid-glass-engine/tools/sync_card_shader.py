"""Share the app card's exact shader with the separately compiled SystemUI module.
No second optical implementation. Run by Gradle before Java compilation.
"""
from pathlib import Path
import json,re
root=Path(__file__).resolve().parent.parent
src=root/'src/main/kotlin/com/example/remote_control/glasscard'
def literal(name):
 return re.search(r'const val SHADER="""(.*?)"""', (src/name).read_text(encoding='utf-8'), re.S).group(1)
s=(src/'CardCompositorMaterial.kt').read_text(encoding='utf-8')
parts=re.findall(r'"""(.*?)"""',s,re.S)
assert len(parts)==2, 'Card shader literal structure changed; update generator explicitly'
shader=parts[0]+literal('GlassReaction.kt')+literal('GlassTouchRipples.kt')+parts[1]
# Chunk only at source lines; Java constant stays below UTF8 constant-pool limit.
lines=shader.splitlines(keepends=True)
body='package com.nodecockpit.customization;\n// Generated by scripts/sync_card_shader.py; upstream MIT attribution retained in app assets.\nfinal class CardLiquidShader { static final String SOURCE=\n'+'+\n'.join(json.dumps(x,ensure_ascii=True) for x in lines)+';\n}\n'
target=root/'src/main/java/com/nodecockpit/customization/CardLiquidShader.java'
if not target.exists() or target.read_text(encoding='utf-8')!=body:target.write_text(body,encoding='utf-8')
